def build_list_chain(actions, prefix, list_title, fields, prev):
    """1リスト分の直列チェーンを actions に追加し、最後のアクション名を返す。
    prefix: 'Ledger' / 'RunLog'。参照フロー踏襲＋列存在チェックによる冪等化。"""
    ct = "Compose_" + prefix + "ListTitle"

    # 1. リスト名定数（Compose。変数不使用＝自己参照事故ゼロ）
    actions[ct] = {"type": "Compose", "inputs": list_title,
                   "runAfter": ({} if prev is None else {prev: ["Succeeded"]})}

    # 2. リスト作成（既存なら失敗するが、次のGetで継続する半冪等パターン=参照フロー踏襲）
    create_body = json.dumps({"__metadata": {"type": "SP.List"}, "AllowContentTypes": True,
                              "BaseTemplate": 100, "ContentTypesEnabled": True,
                              "Title": "@{trim(coalesce(outputs('" + ct + "'), ''))}"}, ensure_ascii=False)
    actions["Create_" + prefix + "List"] = http("POST", "_api/web/lists", dict(H_VERBOSE), create_body,
                                                {ct: ["Succeeded"]})

    # 3. リスト取得（作成の成否に関わらず実行=既存リストでも継続）
    get_uri = ("@concat('_api/web/lists/GetByTitle(''', trim(outputs('" + ct + "')), "
               "''')?$select=Id,Title&$expand=RootFolder')")
    actions["Get_" + prefix + "List"] = http("GET", get_uri, dict(H_NOMETA), None,
                                             {"Create_" + prefix + "List": ["Succeeded", "Skipped", "Failed", "TimedOut"]})

    # 4. リストID保持（Lookup不要だが指示§4.2どおり保持。レポート・拡張用）
    actions["Compose_" + prefix + "ListId"] = {"type": "Compose",
        "inputs": "@trim(string(body('Get_" + prefix + "List')?['Id']))",
        "runAfter": {"Get_" + prefix + "List": ["Succeeded"]}}

    # 5. 既存列一覧の取得（冪等化の基礎）
    fields_uri = ("@concat('_api/web/lists/GetByTitle(''', trim(outputs('" + ct + "')), "
                  "''')/fields?$select=Title,InternalName,TypeAsString')")
    actions["Get_" + prefix + "ExistingFields"] = http("GET", fields_uri, dict(H_NOMETA), None,
                                                       {"Compose_" + prefix + "ListId": ["Succeeded"]})
    prev_a = "Get_" + prefix + "ExistingFields"

    # 6. 列ごと: 存在チェック（Filter）→ 無ければ作成（If内 createFieldAsXml）
    caf_uri = ("@concat('_api/web/lists/GetByTitle(''', trim(outputs('" + ct + "')), "
               "''')/fields/createFieldAsXml')")
    for fname, ftype in fields:
        flt = "Filter_" + prefix + "_" + fname
        cnd = "If_Create_" + prefix + "_" + fname
        actions[flt] = {"type": "Query",
            "inputs": {"from": "@coalesce(body('Get_" + prefix + "ExistingFields')?['value'], json('[]'))",
                       "where": "@equals(coalesce(item()?['InternalName'], ''), '" + fname + "')"},
            "runAfter": {prev_a: ["Succeeded"]}}
        # length()==0 の整数比較（型曖昧性ゼロ。実環境インポート実績のある形式）
        actions[cnd] = {"type": "If",
            "expression": {"and": [{"equals": ["@length(body('" + flt + "'))", 0]}]},
            "actions": {"Create_" + prefix + "_" + fname:
                        http("POST", caf_uri, dict(H_VERBOSE), create_field_body(fname, ftype), {})},
            "runAfter": {flt: ["Succeeded"]}}
        prev_a = cnd

    # 7. 既定ビュー再構築: 全削除 → 最終列一覧 → 列ごとに実InternalNameを取得して追加
    actions["Remove_" + prefix + "DefaultViewFields"] = http(
        "POST",
        "@concat('_api/web/lists/GetByTitle(''', trim(outputs('" + ct + "')), ''')/defaultView/viewfields/removeAllViewFields()')",
        dict(H_NOMETA), None, {prev_a: ["Succeeded"]})
    actions["Get_" + prefix + "FinalFields"] = http("GET", fields_uri, dict(H_NOMETA), None,
                                                    {"Remove_" + prefix + "DefaultViewFields": ["Succeeded"]})
    prev_a = "Get_" + prefix + "FinalFields"

    def add_view_literal(field_literal, after):
        """システム列（LinkTitle/Author等）は固定内部名で直接追加"""
        name = "Add_" + prefix + "ViewField_" + field_literal
        # 生成されるURI例: _api/web/lists/GetByTitle('MeetingArchiveLedger')/defaultView/viewfields/AddViewField('LinkTitle')
        uri = ("@concat('_api/web/lists/GetByTitle(''', trim(outputs('" + ct + "')), "
               "''')/defaultView/viewfields/AddViewField(''" + field_literal + "'')')")
