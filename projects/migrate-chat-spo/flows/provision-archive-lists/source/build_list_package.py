def schema_xml(name, ftype):
    """createFieldAsXml 用の Field XML（不要な属性は付与しない）"""
    if ftype == "Text":
        return ('<Field Type="Text" DisplayName="' + name + '" Name="' + name +
                '" Required="FALSE" Group="AutoGenerated Columns" MaxLength="255" />')
    if ftype == "Note":
        return ('<Field Type="Note" DisplayName="' + name + '" Name="' + name +
                '" Required="FALSE" Group="AutoGenerated Columns" RichText="FALSE" NumLines="6" />')
    if ftype == "Number":
        # Decimals未指定=自動（整数はそのまま表示）。不要属性は付与しない。
        return ('<Field Type="Number" DisplayName="' + name + '" Name="' + name +
                '" Required="FALSE" Group="AutoGenerated Columns" />')
    raise ValueError(ftype)


def create_field_body(name, ftype):
    """createFieldAsXml のボディ（JSON文字列。参照フローと同じ parameters ラッパ＋Options 0）"""
    return json.dumps({"parameters": {"__metadata": {"type": "SP.XmlSchemaFieldCreationInformation"},
                                      "Options": 0, "SchemaXml": schema_xml(name, ftype)}},
                      ensure_ascii=False)


